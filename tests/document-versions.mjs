import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { webcrypto } from 'node:crypto';
const context = vm.createContext({ crypto: webcrypto });
vm.runInContext(fs.readFileSync(new URL('../document-editor.js', import.meta.url), 'utf8'), context);
const model = context.CarijoVersions;
let versions = model.append([], '<p>Original</p>', 'Original', 'Original');
assert.equal(model.append(versions, '<p>Original</p>', 'Original'), versions, 'No duplicate checkpoints');
const original = versions[0].id;
for (let i = 0; i < 40; i++) versions = model.append(versions, `<p>${i}</p>`, `${i}`);
assert.equal(versions.length, 30);
assert.equal(versions[0].id, original, 'Keep original after pruning');
const latest = versions.at(-1).id;
versions = model.append(versions, versions[0].html, versions[0].text, 'Versão restaurada');
assert.equal(versions.at(-1).text, 'Original');
assert(versions.some(x => x.id === latest), 'Restore does not erase the last edit');
const diff = model.compare('Objetivo\nAntigo', 'Objetivo\nNovo');
assert.equal(diff.before[0].changed, false);
assert.equal(diff.before[1].changed, true);
assert.equal(diff.after[1].changed, true);
const malicious = model.compare('<script>alert(1)</script>', 'Seguro');
assert.equal(malicious.before[0].text, '<script>alert(1)</script>', 'Diff remains text, never markup');
const source = fs.readFileSync(new URL('../document-editor.js', import.meta.url), 'utf8');
assert(source.includes('revision === session.revision'));
assert(source.includes('currentUser?.id !== owner'));
assert(source.includes('queue.catch(() => {}).then(operation)'));
assert(source.includes('sanitizeDocumentHtml(version.html)'));
console.log('Document versions: deduplication, 30-checkpoint retention, non-destructive restore, safe text comparison and save guards passed.');
