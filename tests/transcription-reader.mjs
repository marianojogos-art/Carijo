import assert from 'node:assert/strict';
import {recognizeLocalText} from '../local-readers.mjs';
const text='01) A\n02)  1,50 + 002 = 3,50\n03)\n04) não sei\n';
let terminated=0,calls=0;
globalThis.window={Tesseract:{createWorker:async()=>({recognize:async()=>{calls++;return {data:{text,words:[{text:'01)',confidence:99},{text:'002',confidence:35},{text:'não',confidence:92}]}};},terminate:async()=>{terminated++;}})}};
assert.deepEqual(await recognizeLocalText({synthetic:true}),{text,uncertainWords:['002'],hasConfidence:true});
assert.equal(terminated,1);
const alreadyCancelled=new AbortController();alreadyCancelled.abort();
await assert.rejects(recognizeLocalText({},null,alreadyCancelled.signal),/cancelada/);assert.equal(calls,1);
let initialize;
window.Tesseract.createWorker=()=>new Promise(resolve=>initialize=resolve);
const initializing=new AbortController(),pendingInit=recognizeLocalText({},null,initializing.signal);
initializing.abort();initialize({recognize(){throw new Error('Must not recognize after cancellation');},terminate:async()=>{terminated++;}});
await assert.rejects(pendingInit,/cancelada/);assert.equal(terminated,2);
let started;
const recognitionStarted=new Promise(resolve=>started=resolve);
window.Tesseract.createWorker=async()=>({recognize(){started();return new Promise(()=>{});},terminate:async()=>{terminated++;}});
const running=new AbortController(),pending=recognizeLocalText({},null,running.signal);await recognitionStarted;running.abort();
await assert.rejects(pending,/cancelada/);assert.equal(terminated,3);
window.Tesseract.createWorker=async()=>({recognize:async()=>{throw new Error('Mock failure');},terminate:async()=>{terminated++;}});
await assert.rejects(recognizeLocalText({}),/Mock failure/);assert.equal(terminated,4);
window.Tesseract.createWorker=async()=>({recognize:async()=>({data:{text:''}}),terminate:async()=>{terminated++;}});
assert.deepEqual(await recognizeLocalText({}),{text:'',uncertainWords:[],hasConfidence:false});
console.log('OCR simulado: números, espaços, linhas, baixa confiança, vazio, falha e cancelamento com descarte do worker verificados.');
